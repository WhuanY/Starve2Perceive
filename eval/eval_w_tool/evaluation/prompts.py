# ICE (In-Context Examples) style prompt for lasj - same as fixretina reward_score
JUDGE_PROMPT_ICE_TEMPLATE = """Below are two answers to a question. Question is [Question], [Standard Answer] is the standard answer to the question, and [Model_answer] is the answer extracted from a model's output to this question.  Determine whether these two answers are consistent.
Note that [Model Answer] is consistent with [Standard Answer] whenever they are essentially the same. If the meaning is expressed in the same way, it is considered consistent, for example, 'pink' and 'it is pink'.

If they are consistent, Judement is 1; if they are different, Judement is 0. Just output Judement and don't output anything else.\n\n
"""


def get_chat_template():
    """Chat template for lasj ICE prompt (from fixretina)."""
    return JUDGE_PROMPT_ICE_TEMPLATE


def get_prompt(predict_str: str, ground_truth: str, question: str) -> str:
    """Build full lasj prompt with ICE (from fixretina)."""
    examples = get_gpt4_score_ICE()
    chat_template = get_chat_template()
    demo_prompt = chat_template
    for example in examples:
        demo_prompt += example + '\n\n'
    ground_truth_str = str(ground_truth) if isinstance(ground_truth, list) else ground_truth
    test_prompt = f"""
[Question]: {question}
[Standard Answer]: {ground_truth_str}
[Model_answer] : {predict_str}
Judgement:"""
    return demo_prompt + test_prompt

